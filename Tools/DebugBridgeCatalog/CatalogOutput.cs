using System.Text;
using System.Text.Json;

namespace DebugBridgeCatalog;

internal static class CatalogOutput
{
    internal const string ReferencePath = ".agentic/DEBUG_BRIDGE_REFERENCE.md";
    internal const string JsonPath = ".agentic/debug-bridge/catalog.json";

    internal static IReadOnlyDictionary<string, string> Render(CatalogDocument catalog)
        => new Dictionary<string, string>(StringComparer.Ordinal)
        {
            [ReferencePath] = Markdown(catalog),
            [JsonPath] = JsonSerializer.Serialize(catalog, CatalogDocument.JsonOptions).Replace("\r\n", "\n") + "\n",
        };

    internal static IReadOnlyList<string> Check(string root, IReadOnlyDictionary<string, string> expected)
    {
        var errors = new List<string>();
        foreach (var (relativePath, content) in expected)
        {
            var path = Path.Combine(root, relativePath);
            if (!File.Exists(path))
                errors.Add("Missing generated file: " + relativePath);
            else if (!File.ReadAllBytes(path).AsSpan().SequenceEqual(Encoding.UTF8.GetBytes(content)))
                errors.Add("Stale generated file: " + relativePath);
        }
        // This directory is exclusively generated; the hand-maintained protocol guide lives beside it.
        var generatedDirectory = Path.Combine(root, ".agentic", "debug-bridge");
        if (Directory.Exists(generatedDirectory))
        {
            foreach (var file in Directory.EnumerateFiles(generatedDirectory, "*", SearchOption.AllDirectories))
            {
                var relative = Path.GetRelativePath(root, file).Replace('\\', '/');
                if (!expected.ContainsKey(relative))
                    errors.Add("Obsolete generated file: " + relative);
            }
        }
        return errors;
    }

    internal static void Write(string root, IReadOnlyDictionary<string, string> output)
    {
        foreach (var (relativePath, content) in output)
        {
            var path = Path.Combine(root, relativePath);
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, content, new UTF8Encoding(false));
        }
    }

    private static string Markdown(CatalogDocument catalog)
    {
        var text = new StringBuilder();
        void Line(string value = "") => text.Append(value).Append('\n');
        Line("# TiXL Debug Bridge command reference");
        Line();
        Line("Generated from `Tools/DebugBridgeCatalog/Catalog/*.json`. Do not edit this file directly.");
        Line();
        Line($"Catalog format: {catalog.FormatVersion}. Bridge protocol version: {catalog.ProtocolVersion}. This describes JSON lines over local TCP, not HTTP or OpenAPI.");
        Line();
        Line("Command names are checked against source dispatch; verification IDs resolve to test methods. These checks do not prove that every behavior or target passed. See the [coverage and evidence ledger](../Tests/Editor.IntegrationTests/DebugBridgeCoverage.md) for pending cases, known limitations and runner prerequisites.");
        Line();
        Line("Use [getVersion](#getversion) to identify the running bridge, [getContext](#getcontext) for the active project/selection, and [getGraphState](#getgraphstate) for a known composition. No live `describe` command or operator index is added. See the [protocol guide](DEBUG_PROTOCOL.md) for transport, evaluation and safe client usage, or load the [machine-readable catalog](debug-bridge/catalog.json) in external tooling.");
        Line();
        Line("## Targets");
        Line();
        Line("Availability below means a callable dispatch name. Individual handlers can reject a platform or lack required devices/resources.");
        Line();
        foreach (var target in catalog.Targets)
            Line($"- **{Escape(target.Name)}**: conditional symbols `{string.Join(", ", target.Symbols)}`.");
        Line();
        Line("## Commands");
        Line();
        foreach (var command in catalog.Commands)
            Line($"- [{Escape(command.Name)}](#{command.Name.ToLowerInvariant()}) — {Escape(command.Summary)}");
        foreach (var command in catalog.Commands)
        {
            Line();
            Line("## " + Escape(command.Name));
            Line();
            Line(Escape(command.Summary));
            Line();
            Line("Targets: " + string.Join(", ", command.Targets.Select(Escape)) + ".");
            if (command.AliasOf != null)
                Line("Alias of: " + Escape(command.AliasOf) + ".");
            Line();
            if (command.Arguments.Length == 0)
                Line("No command-specific arguments.");
            else
            {
                Line("| Argument | Wire type | Required | Meaning | Omission / default |");
                Line("| --- | --- | --- | --- | --- |");
                foreach (var argument in command.Arguments)
                {
                    var defaultText = argument.Default.ValueKind == JsonValueKind.Undefined ? "" : " Documented default: " + argument.Default.GetRawText();
                    Line($"| {Escape(argument.Name)} | {Escape(argument.WireType)} | {(argument.Required ? "Yes" : "No")} | {Escape(argument.Description)} | {Escape(argument.OmissionBehavior + defaultText)} |");
                }
            }
            Line();
            Line("**Result:** " + Escape(command.Result));
            Line();
            Line("**Errors:** " + (command.Errors.Length == 0 ? "No command-specific errors listed." : string.Join(", ", command.Errors.Select(Escape)) + ".") + " Conversion/evaluation exceptions can also produce INTERNAL_ERROR; malformed envelopes have transport-level behavior.");
            Line();
            Line("**Effects:** " + Escape(command.Effects));
            Line();
            Line("**Completion:** " + Escape(command.Completion));
            Line();
            Line("**Verification references** (execution status is recorded separately):");
            Line();
            foreach (var id in command.VerificationIds)
                Line("- " + Escape(id));
            if (command.Extensions is { Count: > 0 })
            {
                Line();
                Line("**Examples and additional metadata:**");
                Line();
                Line("```json");
                Line(JsonSerializer.Serialize(command.Extensions, CatalogDocument.JsonOptions).Replace("\r\n", "\n"));
                Line("```");
            }
        }
        return text.ToString();
    }

    private static string Escape(string value)
        => value.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;")
                .Replace("|", "&#124;").Replace("`", "&#96;").Replace("\r\n", "\n").Replace("\n", "<br>");
}
